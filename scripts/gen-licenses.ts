// 由安装包里实际带上的依赖生成 THIRD_PARTY_LICENSES.md（v0.10）。
// 用法：pnpm licenses（改了依赖后运行；单元测试会检查两者一致）。
// 两类依赖会进安装包：dependencies（连同它们的依赖）原样放进应用包；外壳页面打包进去的库见 BUNDLED。
// Electron 与 Chromium 的许可证另外随应用分发：Windows 由 electron-builder 自动放进安装目录，
// macOS 由 electron-builder.yml 的 mac.extraResources 放进 Resources（LICENSE.electron.txt、LICENSES.chromium.html）。
import { existsSync, readFileSync, readdirSync, realpathSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'

const ROOT = resolve(__dirname, '..')
export const LICENSES_MD = resolve(ROOT, 'THIRD_PARTY_LICENSES.md')

/** 外壳（renderer）构建时打进 out/renderer 的库：它们在 devDependencies 里，但会随安装包分发 */
export const BUNDLED = ['react', 'react-dom', 'zustand']

interface Pkg {
  name: string
  version: string
  license: string
  homepage: string
  text: string
  dir: string
  deps: string[]
}

/** 按 Node 的查找规则从 from 往上找 node_modules/<name>；pnpm 的依赖与它的兄弟同在一个 node_modules 里 */
function findPkg(name: string, from: string): string | null {
  for (let dir = from; ; dir = dirname(dir)) {
    const cand = join(dir, 'node_modules', name, 'package.json')
    if (existsSync(cand)) return realpathSync(dirname(cand))
    if (dirname(dir) === dir) return null
  }
}

function readPkg(dir: string): Pkg {
  const pj = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8')) as {
    name: string
    version: string
    license?: string
    homepage?: string
    repository?: string | { url?: string }
    dependencies?: Record<string, string>
  }
  const file = readdirSync(dir).find((f) => /^(licen[cs]e|copying)(\.|$)/i.test(f))
  const repo = typeof pj.repository === 'string' ? pj.repository : pj.repository?.url
  return {
    name: pj.name,
    version: pj.version,
    license: pj.license ?? 'UNKNOWN',
    homepage: pj.homepage ?? repo?.replace(/^git\+/, '').replace(/\.git$/, '') ?? '',
    text: file ? readFileSync(join(dir, file), 'utf8').trim() : '',
    dir,
    deps: Object.keys(pj.dependencies ?? {})
  }
}

/** 从根 package.json 的 dependencies 与 BUNDLED 出发，收集要随安装包分发的全部包 */
export function collect(root = ROOT): Pkg[] {
  const top = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8')) as { dependencies?: Record<string, string> }
  const seen = new Map<string, Pkg>()
  const visit = (name: string, from: string): void => {
    const dir = findPkg(name, from)
    if (!dir) throw new Error(`[licenses] cannot find ${name} from ${from}`)
    const p = readPkg(dir)
    const key = `${p.name}@${p.version}`
    if (seen.has(key)) return
    seen.set(key, p)
    for (const d of p.deps) visit(d, dir)
  }
  for (const name of [...Object.keys(top.dependencies ?? {}), ...BUNDLED]) visit(name, root)
  return [...seen.values()].sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version))
}

export function renderLicenses(pkgs: Pkg[]): string {
  const lines = [
    '# Third-party notices',
    '',
    'Twiq includes the open-source software listed below. Each entry gives the package, its version and license, followed by the license text.',
    '',
    'Twiq 的安装包里包含下列开源软件，每一项列出包名、版本、许可证与许可证全文。',
    '',
    'Electron and Chromium licenses ship with the app as `LICENSE.electron.txt` and `LICENSES.chromium.html` (in the install folder on Windows, in `Twiq.app/Contents/Resources` on macOS).',
    '',
    '<!-- Generated by scripts/gen-licenses.ts (pnpm licenses). Do not edit by hand. -->',
    ''
  ]
  for (const p of pkgs) {
    lines.push(`## ${p.name} ${p.version}`, '', `License: ${p.license}${p.homepage ? ` · ${p.homepage}` : ''}`, '')
    lines.push(p.text ? ['```text', p.text, '```'].join('\n') : '_No license file in the package; see the license field above._', '')
  }
  return lines.join('\n')
}

if (require.main === module) {
  const pkgs = collect()
  writeFileSync(LICENSES_MD, renderLicenses(pkgs))
  console.log(`wrote ${LICENSES_MD} (${pkgs.length} packages: ${pkgs.map((p) => p.name).join(', ')})`)
}
